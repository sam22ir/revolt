/**
 * Gettext `.po` export of the locales for the Godot client. Pure; `scripts/export-godot.mjs` writes the files to
 * `apps/godot/locale/` and a test fails when they are stale.
 *
 * `msgid` is the dotted key (`building.hq.name`), so `tr("building.hq.name")` works in Godot, including the
 * `background.<id>.<key>` overrides. i18next's `{{name}}` becomes Godot's `{name}` for `String.format()`.
 */
import { ar } from "./locales/ar.ts";
import { en } from "./locales/en.ts";
import { fr } from "./locales/fr.ts";

export type PoLanguage = "en" | "fr" | "ar";

const LOCALES: Readonly<Record<PoLanguage, object>> = { en, fr, ar };

/** Plural rules per language (CLDR), for when a key starts needing plural forms. */
const PLURAL_FORMS: Readonly<Record<PoLanguage, string>> = {
  en: "nplurals=2; plural=(n != 1);",
  fr: "nplurals=2; plural=(n > 1);",
  ar: "nplurals=6; plural=(n==0 ? 0 : n==1 ? 1 : n==2 ? 2 : n%100>=3 && n%100<=10 ? 3 : n%100>=11 ? 4 : 5);",
};

export const flattenLocale = (obj: object, prefix = ""): [string, string][] =>
  Object.entries(obj).flatMap(([k, v]): [string, string][] =>
    typeof v === "string" ? [[`${prefix}${k}`, v]] : flattenLocale(v as object, `${prefix}${k}.`),
  );

/** `{{count}}` -> `{count}`. Throws on interpolation features the Godot side does not support. */
export const toGodotPlaceholders = (key: string, text: string): string => {
  const out = text.replace(/\{\{(\w+)\}\}/g, "{$1}");
  if (/\{\{|\}\}|\$t\(/.test(out)) throw new Error(`unsupported i18next syntax in ${key}: ${text}`);
  return out;
};

const quote = (s: string): string =>
  `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\t/g, "\\t")}"`;

export const buildPo = (lang: PoLanguage): string => {
  const header = [
    'msgid ""',
    'msgstr ""',
    `"Language: ${lang}\\n"`,
    '"MIME-Version: 1.0\\n"',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    `"Plural-Forms: ${PLURAL_FORMS[lang]}\\n"`,
  ].join("\n");
  const entries = flattenLocale(LOCALES[lang]).map(
    ([key, text]) => `msgid ${quote(key)}\nmsgstr ${quote(toGodotPlaceholders(key, text))}`,
  );
  return `# Generated by scripts/export-godot.mjs from apps/client/src/i18n/locales. Do not edit.\n${header}\n\n${entries.join("\n\n")}\n`;
};

export const PO_LANGUAGES: readonly PoLanguage[] = ["en", "ar", "fr"];
